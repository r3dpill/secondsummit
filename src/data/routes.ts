/**
 * Route data for the elevation tracker.
 *
 * Carried over verbatim from the Live Tracking page on wisecoasttocoast.com —
 * the profile came from GPX with peaks corrected to true OS heights, the
 * overnights from the itinerary, and the waypoints are the ~444 GPS points
 * used to place a live InReach position onto a route mile.
 *
 * Do not retype these numbers by hand; they were extracted from the original.
 */

/** [cumulative miles, elevation in metres, optional label] */
export type RoutePoint = [number, number, string?];

/** [latitude, longitude, cumulative miles] */
export type Waypoint = [number, number, number];

export type StayType = 'pub' | 'camp' | 'iconic' | 'hotel' | 'bnb' | 'campsite' | 'finish';

export interface DayMarker {
  day: number;
  /** Cumulative miles at the end of the day — where the dot sits. */
  endMile: number;
  /** Place name. */
  label: string;
  type: StayType;
  /** Where he actually slept. */
  name: string;
  /** Distance walked that day, free text. */
  dist: string;
  /** Optional website for the accommodation. */
  url?: string;
}

export interface Region {
  start: number;
  end: number;
  label: string;
  color: string;
}

export interface RouteData {
  /** Shown above the chart. */
  title: string;
  subtitle: string;
  route: RoutePoint[];
  days: DayMarker[];
  regions: Region[];
  waypoints: Waypoint[];
  /** Labels always drawn above the profile. */
  summitLabels: string[];
  /** Labels drawn only where there is room. */
  townLabels: string[];
  /** Given a backdrop so they stay readable over the profile. */
  keyTowns: string[];
  /** Called out with a marker on the chart. */
  highestPoint?: string;
  /** Axis ceilings. */
  maxMile: number;
  maxElev: number;
  /** Tick positions. */
  mileTicks: number[];
  elevTicks: number[];
  /** Labels at either end of the profile, e.g. the two seas. */
  startLabel?: string;
  endLabel?: string;
  /** Live tracking on this route, or a finished walk? */
  live: boolean;
  /** Label for the moving position marker. */
  walkerLabel: string;
  /** Past this mile the marker switches label (Ben joined at Richmond). */
  walkerLabelSwitchMile?: number;
  walkerLabelAfter?: string;
}

